def get_by_l1(l1: str) -> list:
    return [c for c in XZSC_CHAINS if c["l1"] == l1]


def get_by_name(name: str) -> dict:
    for c in XZSC_CHAINS:
        if c["name"] == name:
            return c
    return None


def stats() -> dict:
    from collections import Counter
    l1_counter = Counter(c["l1"] for c in XZSC_CHAINS)
    return {
        "total": len(XZSC_CHAINS),
        "l1_themes": len(l1_counter),
        "by_l1": dict(l1_counter),
        "source_name": SOURCE_NAME,
        "source_url": SOURCE_URL,
    }


