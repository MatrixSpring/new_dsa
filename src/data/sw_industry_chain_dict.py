def _parse_l3_data():
    """解析 L3 原始数据为结构化字典列表"""
    items = []
    for row in _L3_DATA:
        code, l1, l2, l3 = row[0], row[1], row[2], row[3]
        upstream = [x.strip() for x in row[4].split(",") if x.strip()]
        downstream = [x.strip() for x in row[5].split(",") if x.strip()]
        lf = LEADERS_FACTORS.get(l3, {})
        items.append({
            "code": code, "l1_name": l1, "l2_name": l2, "l3_name": l3,
            "upstream": upstream, "downstream": downstream,
            "leaders": lf.get("leaders", ""), "factors": lf.get("factors", ""),
        })
    return items

