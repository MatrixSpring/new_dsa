def get_all_groups():
    groups = set()
    for item in SW_CHAIN_DICT["items"]:
        for up in item["upstream"]:
            groups.add(f"{up} -> {item['l3_name']}")
        for dn in item["downstream"]:
            groups.add(f"{item['l3_name']} -> {dn}")
    return sorted(groups)

def get_upstream(name, max_depth=3):
    visited = {name}
    queue = deque([(name, 0)])
    result = []
    while queue:
        curr, depth = queue.popleft()
        if depth >= max_depth:
            continue
        for neighbor, direction in _ADJ.get(curr, []):
            if direction == "up" and neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, depth + 1))
                item = _NAME_INDEX.get(neighbor)
                if item:
                    item_copy = dict(item)
                    item_copy["depth"] = depth + 1
                    result.append(item_copy)
    return result

def get_downstream(name, max_depth=3):
    visited = {name}
    queue = deque([(name, 0)])
    result = []
    while queue:
        curr, depth = queue.popleft()
        if depth >= max_depth:
            continue
        for neighbor, direction in _ADJ.get(curr, []):
            if direction == "down" and neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, depth + 1))
                item = _NAME_INDEX.get(neighbor)
                if item:
                    item_copy = dict(item)
                    item_copy["depth"] = depth + 1
                    result.append(item_copy)
    return result

def get_chain_path(start, end, max_depth=6):
    if start == end:
        return [start]
    visited = {start}
    queue = deque([(start, [start])])
    while queue:
        curr, path = queue.popleft()
        if len(path) > max_depth:
            continue
        for neighbor, _ in _ADJ.get(curr, []):
            if neighbor == end:
                return path + [neighbor]
            if neighbor not in visited:
                visited.add(neighbor)
                queue.append((neighbor, path + [neighbor]))
    return None

def find_affected_chains(event_keyword):
    kw = event_keyword.lower()
    affected = []
    for item in SW_CHAIN_DICT["items"]:
        all_text = " ".join([
            item["l1_name"], item["l2_name"], item["l3_name"],
            " ".join(item["upstream"]), " ".join(item["downstream"]),
            item["leaders"], item["factors"]
        ]).lower()
        if kw in all_text:
            affected.append(item)
    return affected

def get_chain_graph(l3_name=None, l1_name=None):
    if l3_name:
        items = [get_by_name(l3_name)] + get_upstream(l3_name) + get_downstream(l3_name)
        items = [x for x in items if x]
    elif l1_name:
        items = get_by_l1(l1_name)
    else:
        items = SW_CHAIN_DICT["items"]
    nodes = []
    edges = []
    seen = set()
    for item in items:
        if item["code"] not in seen:
            seen.add(item["code"])
            nodes.append({
                "id": item["code"], "name": item["l3_name"],
                "l1": item["l1_name"], "l2": item["l2_name"],
                "category": item["l1_name"],
                "leaders": item["leaders"], "factors": item["factors"],
            })
        for up in item["upstream"]:
            up_item = _NAME_INDEX.get(up)
            if up_item and up_item["code"] not in seen:
                seen.add(up_item["code"])
                nodes.append({"id": up_item["code"], "name": up_item["l3_name"],
                              "l1": up_item["l1_name"], "l2": up_item["l2_name"],
                              "category": up_item["l1_name"]})
            if up_item:
                edges.append({"source": up_item["code"], "target": item["code"], "type": "upstream"})
        for dn in item["downstream"]:
            dn_item = _NAME_INDEX.get(dn)
            if dn_item and dn_item["code"] not in seen:
                seen.add(dn_item["code"])
                nodes.append({"id": dn_item["code"], "name": dn_item["l3_name"],
                              "l1": dn_item["l1_name"], "l2": dn_item["l2_name"],
                              "category": dn_item["l1_name"]})
            if dn_item:
                edges.append({"source": item["code"], "target": dn_item["code"], "type": "downstream"})
    categories = [{"name": l1} for l1 in L1_NAMES]
    return {"nodes": nodes, "edges": edges, "categories": categories}

def export_json(filepath=None):
    data = json.dumps(SW_CHAIN_DICT, ensure_ascii=False, indent=2)
    if filepath:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(data)
    return data

def export_sql(filepath=None):
    lines = ["CREATE TABLE IF NOT EXISTS sw_industry_chain (",
             "    code TEXT PRIMARY KEY,",
             "    l1_name TEXT, l2_name TEXT, l3_name TEXT,",
             "    upstream TEXT, downstream TEXT, leaders TEXT, factors TEXT",
             ");"]
    for item in SW_CHAIN_DICT["items"]:
        up = ",".join(item["upstream"])
        dn = ",".join(item["downstream"])
        lines.append(
            f"INSERT INTO sw_industry_chain VALUES ("
            f"'{item['code']}','{item['l1_name']}','{item['l2_name']}',"
            f"'{item['l3_name']}','{up}','{dn}',"
            f"'{item['leaders']}','{item['factors']}');"
        )
    sql = "\n".join(lines)
    if filepath:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write(sql)
    return sql

