# 邻接表 (BFS 查询用)
_ADJ = defaultdict(list)
_CODE_INDEX = {}
_NAME_INDEX = {}
for _item in SW_CHAIN_DICT["items"]:
    _CODE_INDEX[_item["code"]] = _item
    _NAME_INDEX[_item["l3_name"]] = _item
    for up in _item["upstream"]:
        _ADJ[up].append((_item["l3_name"], "down"))
        _ADJ[_item["l3_name"]].append((up, "up"))
    for dn in _item["downstream"]:
        _ADJ[dn].append((_item["l3_name"], "up"))
        _ADJ[_item["l3_name"]].append((dn, "down"))


